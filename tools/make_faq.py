#!/usr/bin/env python3
"""Write FAQ.md from the questions and answers of the program's Help tab (helper/rwtranslate/i18n.py), Portuguese and English,
so the page on GitHub and the window never disagree. Run: python tools/make_faq.py   (`--check` only verifies the file is up to date)."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "helper"))


def build():
    from rwtranslate import i18n

    def section(lang):
        out = []
        for i in range(1, i18n.faq_count() + 1):
            q, a = i18n.TEXT[lang][f"faq_q{i}"], i18n.TEXT[lang][f"faq_a{i}"]
            a = a.replace("%LOCALAPPDATA%\\RimWorldAutoTranslate", "`%LOCALAPPDATA%\\RimWorldAutoTranslate`")
            out.append(f"### {i}. {q}\n\n{a}\n")
        return "\n".join(out)
    return f"""<h1 align="center">FAQ</h1>

<p align="center">
<a href="#portugu%C3%AAs"><img src="https://img.shields.io/badge/PERGUNTAS-PORTUGU%C3%8AS-2ea44f?style=for-the-badge" alt="Português"></a>
<a href="#english"><img src="https://img.shields.io/badge/QUESTIONS-ENGLISH-2ea44f?style=for-the-badge" alt="English"></a>
</p>

<p align="center"><a href="README.md">&larr; README</a></p>

<!-- Generated by tools/make_faq.py from the Help tab of the program (helper/rwtranslate/i18n.py). Do not edit by hand. -->

## Português

{section("pt")}
---

## English

{section("en")}"""


def main(argv):
    path = ROOT / "FAQ.md"
    text = build()
    if "--check" in argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print("FAQ.md is out of date: run python tools/make_faq.py")
            return 1
        print("OK FAQ.md")
        return 0
    path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
